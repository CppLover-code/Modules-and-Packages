"""
Модуль sched и выполнение действий по расписанию

Модуль sched предоставляет гибкий и удобный способ для планирования задач, 
которые должны быть выполнены в определённое время. Этот модуль идеально подходит 
для ситуаций, когда необходимо выполнять действия с задержкой или через заданные 
интервалы.

Модуль sched основан на концепции планировщика (scheduler), который управляет 
очередью событий. Каждое событие представляет собой вызов функции с заданными 
аргументами. Планировщик использует временную функцию (time function) для 
отслеживания текущего времени и функцию задержки (delay function) для ожидания 
перед выполнением следующего события.

Класс scheduler
class sched.scheduler(timefunc=time.monotonic, delayfunc=time.sleep)
timefunc: функция, возвращающая текущее время. 
delayfunc: функция, которая приостанавливает выполнение на заданное количество секунд.
elayfunc также будет вызываться с аргументом 0 после каждого события, чтобы дать другим 
потокам возможность работать в многопоточных приложениях.
"""

import sched
