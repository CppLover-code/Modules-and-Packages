# Основные команды uv
"""
uv init <project-name>: Создает и инициализирует проект Python с базовой 
структурой

uv venv: Создает в текущем проекте новую виртуальную среду

uv add <package-name>: Добавляет к зависимостям проекта пакет с именем 
package-name

uv pip install -r requirements.txt: Устанавливает все зависимости, указанные 
в файле requirements.txt

uv remove <package-name>: Удаляет пакет из зависимостей проекта

uv run script.py: Запускает скрипт Python или команду внутри проекта

uv sync: Устанавливает все зависимости из файла uv.lock
"""

